-- Run in the PostgreSQL database configured in .env
CREATE TABLE IF NOT EXISTS staging_audience_events (
    event_id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    event_timestamp TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_user (
    user_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dim_event_type (
    event_type_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS fact_audience_events (
    event_id TEXT PRIMARY KEY,
    user_key BIGINT NOT NULL REFERENCES dim_user(user_key),
    event_type_key BIGINT NOT NULL REFERENCES dim_event_type(event_type_key),
    event_timestamp TIMESTAMP NOT NULL
);
